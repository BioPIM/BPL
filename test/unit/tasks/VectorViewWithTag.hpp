template<class ARCH>
struct VectorViewWithTag
{
    USING(ARCH);

    auto operator() (once<vector_view<uint32_t> const&> v) const  {
		return accumulate (*v, uint64_t{0});
    }

    static auto reduce (uint64_t a, uint64_t b) { return a+b; }
};
