template<class ARCH>
struct InplaceVector2
{
    USING(ARCH);

    using type = inplace_vector<uint32_t,100>;

    auto operator() () const  {
    	type res;
    	for (size_t i=0; i<res.capacity()/2; i++) {
    	    res.push_back (i+1);
    	}
    	return res;
    }
};
